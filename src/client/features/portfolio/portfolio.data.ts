const projectKinds: ProjectKind[] = ["oss", "client", "experiments", "snippets", "archived"];

export function portfolio_other_project_groups() {
  const projects = portfolio_other_projects();

  return projectKinds
    .map((kind) => ({
      kind,
      label: portfolio_project_kind_label(kind),
      projects: projects.filter((project) => project.kind === kind),
    }))
    .filter((group) => group.projects.length > 0);
}

function portfolio_project_kind_label(kind: ProjectKind) {
  return {
    oss: m.project_kind_oss,
    client: m.project_kind_client,
    experiments: m.project_kind_experiments,
    snippets: m.project_kind_snippets,
    archived: m.project_kind_archived,
  }[kind]();
}

